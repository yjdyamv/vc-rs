import re, sys
src = open(r'C:\Users\yuan\Desktop\VeraCrypt\src\Volume\EncryptionTest.cpp', encoding='utf-8', errors='replace').read()
start = src.index('XtsTestVectors[] =')
body = src[start:]
end = body.index('\n\t};\n')
body = body[:end]
# strip comments
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
body = re.sub(r'//[^\n]*', '', body)
# find top-level entries { ... }, ... at depth 1
entries = []
depth = 0
cur = None
for ch in body:
    if ch == '{':
        depth += 1
        if depth == 2:  # first inner brace of an entry -> start capturing raw
            cur = ''
            continue
        if depth > 2 and cur is None:
            cur = ''
    if cur is not None:
        cur += ch
    if ch == '}':
        if depth == 3:
            pass
        if depth == 2 and cur is not None:
            entries.append(cur)
            cur = None
        depth -= 1
print("entries:", len(entries), file=sys.stderr)
def nums(s):
    return [int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{1,2})', s)]
out = []
for i, e in enumerate(entries):
    # split on top-level inner brace groups
    groups = []
    d = 0; g = ''
    for ch in e:
        if ch == '{':
            d += 1
            if d == 1: g = ''; continue
        if ch == '}':
            d -= 1
            if d == 0: groups.append(g); continue
        if d >= 1: g += ch
    k1 = nums(groups[0]); k2 = nums(groups[1]); dun = nums(groups[2])
    pt = nums(groups[3]); ct = nums(groups[4])
    assert len(k1)==32 and len(k2)==32 and len(dun)==8, (len(k1),len(k2),len(dun))
    assert len(pt)==512 and len(ct)==512, (len(pt), len(ct))
    out.append((k1,k2,dun,pt,ct))
def hexl(b):
    h = b''.join(bytes(v) for v in [b]).hex() if isinstance(b, (list,)) else ''
    return h
lines = []
lines.append('//! IEEE 1619 XTS-AES-256 known-answer vectors, extracted verbatim from')
lines.append('//! VeraCrypt `src/Volume/EncryptionTest.cpp` (`XtsTestVectors`).')
lines.append('//!')
lines.append('//! Each entry is `(key1_hex, key2_hex, data_unit_no_le_bytes_hex, plaintext_hex, ciphertext_hex)`.')
lines.append('//! The data unit number is the little-endian byte encoding VeraCrypt memcpy\'s into a u64.')
lines.append('//! Generated by tools/gen_xts_kat.py - do not edit by hand.')
lines.append('')
lines.append('pub const XTS_KAT: &[(&str, &str, [u8; 8], &str, &str)] = &[')
for k1,k2,dun,pt,ct in out:
    lines.append('    (')
    lines.append(f'        "{bytes(k1).hex()}",')
    lines.append(f'        "{bytes(k2).hex()}",')
    lines.append(f'        {dun},')
    lines.append(f'        "{bytes(pt).hex()}",')
    lines.append(f'        "{bytes(ct).hex()}",')
    lines.append('    ),')
lines.append('];')
lines.append('')
open(r'C:\Users\yuan\Desktop\vc-rs\crates\vcrs-core\tests\xts_kat_vectors.rs','w').write('\n'.join(lines))
print("wrote %d vectors" % len(out))
